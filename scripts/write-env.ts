/**
 * Writes src/config/env.ts from environment variables, so keys never live in the repo.
 * CI runs it before building: APPLOVIN_SDK_KEY and APPLOVIN_NATIVE_AD_UNIT_ID.
 * With no key set it leaves the committed file alone.
 */
import fs from 'node:fs';
import path from 'node:path';

const sdkKey = process.env.APPLOVIN_SDK_KEY ?? '';
const adUnit = process.env.APPLOVIN_NATIVE_AD_UNIT_ID ?? '';

if (!sdkKey || !adUnit) {
  console.log('No AppLovin key set: keeping sample ads.');
  process.exit(0);
}

const file = path.join(process.cwd(), 'src', 'config', 'env.ts');
fs.writeFileSync(
  file,
  `// GENERATED by scripts/write-env.ts. Do not commit.
export const env = {
  applovinSdkKey: ${JSON.stringify(sdkKey)},
  nativeAdUnitId: ${JSON.stringify(adUnit)},
  adPlaceholders: false,
} as const;
`,
);
console.log('✔ wrote src/config/env.ts (values hidden)');
