/**
 * Writes src/config/env.ts from environment variables, so keys never live in the repo.
 * CI runs it before building. Variables: APPLOVIN_SDK_KEY, APPLOVIN_NATIVE_AD_UNIT_ID,
 * SUPABASE_URL, SUPABASE_ANON_KEY. With none set it leaves the committed file alone.
 */
import fs from 'node:fs';
import path from 'node:path';

const read = (name: string) => (process.env[name] ?? '').trim();

const sdkKey = read('APPLOVIN_SDK_KEY');
const adUnit = read('APPLOVIN_NATIVE_AD_UNIT_ID');
const supabaseUrl = read('SUPABASE_URL').replace(/\/+$/, '');
const supabaseAnonKey = read('SUPABASE_ANON_KEY');

const hasAds = sdkKey.length > 0 && adUnit.length > 0;
const hasSupabase = supabaseUrl.length > 0 && supabaseAnonKey.length > 0;

if (!hasAds && !hasSupabase) {
  console.log('No keys set: keeping sample ads and built-in settings.');
  process.exit(0);
}

const file = path.join(process.cwd(), 'src', 'config', 'env.ts');
fs.writeFileSync(
  file,
  `// GENERATED by scripts/write-env.ts. Do not commit.
export const env = {
  applovinSdkKey: ${JSON.stringify(hasAds ? sdkKey : '')},
  nativeAdUnitId: ${JSON.stringify(hasAds ? adUnit : '')},
  adPlaceholders: ${!hasAds},
  supabaseUrl: ${JSON.stringify(hasSupabase ? supabaseUrl : '')},
  supabaseAnonKey: ${JSON.stringify(hasSupabase ? supabaseAnonKey : '')},
};
`,
);
console.log(`✔ wrote src/config/env.ts (ads: ${hasAds}, remote config: ${hasSupabase}; values hidden)`);
