/**
 * Metro can't read folders at runtime, so this writes one file that imports every reel.
 * Run: npm run content (also part of npm run check).
 */
import fs from 'node:fs';
import path from 'node:path';

const root = path.join(process.cwd(), 'content', 'reels');
const out = path.join(process.cwd(), 'src', 'features', 'content', 'reels.generated.ts');

const list = (kind: string) =>
  fs
    .readdirSync(path.join(root, kind))
    .filter(f => f.endsWith('.json'))
    .sort();

const block = (kind: string, name: string) =>
  `export const ${name}: unknown[] = [\n` +
  list(kind)
    .map(f => `  require('../../../content/reels/${kind}/${f}'),`)
    .join('\n') +
  '\n];\n';

fs.writeFileSync(
  out,
  '// GENERATED by scripts/build-content-index.ts. Do not edit.\n' +
    block('learn', 'learnJson') +
    '\n' +
    block('quiz', 'quizJson'),
);
console.log(`✔ wrote ${path.relative(process.cwd(), out)}`);
